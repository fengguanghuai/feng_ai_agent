-- PostgreSQL/Supabase initialization. Run once against the dedicated project.
-- Unquoted identifiers intentionally fold to lowercase; MyBatis maps labels case-insensitively.
BEGIN;
CREATE TABLE IF NOT EXISTS chat_conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversationId varchar(64) NOT NULL UNIQUE,
    title varchar(255), userId bigint NOT NULL, modelType varchar(32) NOT NULL,
    status smallint NOT NULL DEFAULT 1, isDelete smallint NOT NULL DEFAULT 0,
    createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_conversation_user ON chat_conversation(userId);
CREATE TABLE IF NOT EXISTS chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversationId varchar(64) NOT NULL, content text NOT NULL, role varchar(32) NOT NULL,
    tokens integer DEFAULT 0, isDelete smallint NOT NULL DEFAULT 0,
    createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_message_conversation ON chat_message(conversationId, id);
CREATE TABLE IF NOT EXISTS api_key (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId bigint NOT NULL, apiKey varchar(128) NOT NULL UNIQUE,
    name varchar(64) NOT NULL, modelType varchar(32) NOT NULL,
    status smallint NOT NULL DEFAULT 1, expireTime timestamp,
    createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isDelete smallint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_api_key_user ON api_key(userId);
CREATE TABLE IF NOT EXISTS system_config (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    configKey varchar(64) NOT NULL UNIQUE, configValue text NOT NULL,
    description varchar(255),
    createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isDelete smallint NOT NULL DEFAULT 0
);
-- "user" is a reserved PostgreSQL keyword. User entity uses the portable app_user name.
CREATE TABLE IF NOT EXISTS app_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userAccount varchar(256) NOT NULL UNIQUE, userPassword varchar(512) NOT NULL,
    userName varchar(256), userAvatar varchar(1024), userProfile varchar(512),
    userRole varchar(256) NOT NULL DEFAULT 'user',
    editTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isDelete smallint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_app_user_name ON app_user(userName);
CREATE TABLE IF NOT EXISTS todo_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userId bigint NOT NULL, title varchar(100) NOT NULL, content text,
    status smallint NOT NULL DEFAULT 0, priority smallint NOT NULL DEFAULT 0,
    dueDate timestamp, createTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updateTime timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    isDeleted smallint NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_todo_user ON todo_item(userId);
CREATE INDEX IF NOT EXISTS idx_todo_status ON todo_item(status);
CREATE INDEX IF NOT EXISTS idx_todo_priority ON todo_item(priority);
CREATE INDEX IF NOT EXISTS idx_todo_due ON todo_item(dueDate);

CREATE OR REPLACE FUNCTION public.feng_touch_update_time() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
    NEW.updateTime = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;
DO $$
DECLARE t text;
BEGIN
    FOREACH t IN ARRAY ARRAY['chat_conversation','chat_message','api_key','system_config','app_user','todo_item'] LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid = ('public.' || t)::regclass AND tgname = 'feng_touch_update_time') THEN
            EXECUTE format('CREATE TRIGGER feng_touch_update_time BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.feng_touch_update_time()', t);
        END IF;
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated', t);
    END LOOP;
END;
$$;
COMMIT;
